def para(runs, pp=pp_b, brk=False):
    if first[0]:
        p = doc.paragraphs[0]; first[0] = False
    else:
        p = doc.add_paragraph("")
    p.para_pr_id_ref = pp
    if brk: p.element.set("pageBreak", "1")
    p.clear_text()
